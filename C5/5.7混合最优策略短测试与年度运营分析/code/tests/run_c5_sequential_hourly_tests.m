function report=run_c5_sequential_hourly_tests()
%RUN_C5_SEQUENTIAL_HOURLY_TESTS Regression tests for causal reserve policy.

testRoot=fileparts(mfilename('fullpath'));
codeRoot=fileparts(testRoot);
c5Root=fileparts(fileparts(codeRoot));
addpath(codeRoot,fullfile(c5Root,'5.1场景设计','code'));
c5_add_v5_model_paths();

tests={@test_typhoon_warning_enforces_bess_reserve, ...
    @test_unachievable_reserve_target_is_flagged, ...
    @test_normal_state_floor_preserves_initial_bess, ...
    @test_surplus_redispatch_can_start_pem, ...
    @test_rolling_window_overcomes_pem_start_cost};
names=["typhoon warning reserve target", ...
    "unachievable reserve target fallback", ...
    "normal state floor", ...
    "surplus redispatch starts PEM", ...
    "rolling window starts PEM"];
passed=false(size(tests));
messages=strings(size(tests));
for k=1:numel(tests)
    try
        tests{k}();
        passed(k)=true;
        messages(k)="PASS";
    catch ME
        messages(k)=string(ME.identifier)+": "+string(ME.message);
    end
end
report=table(names',passed',messages', ...
    'VariableNames',{'Test','Passed','Message'});
disp(report);
assert(all(passed),'C5 sequential-hourly regression tests failed.');
end

function test_typhoon_warning_enforces_bess_reserve()
cfg=v5_default_config('mechanism_test');
base=base_case(cfg,1,200);
strategy=struct( ...
    'id','test_typhoon_reserve', ...
    'strategyClass','TEST', ...
    'eventReserveRule',true, ...
    'warningBessReserveTargetSOC',0.80, ...
    'warningH2ReserveTargetKg',0, ...
    'maxENSMWh',Inf);
[summary,ledger]=c5_run_sequential_hourly( ...
    base,cfg,strategy,"TYPHOON_WARNING",false);
assert(summary.allHoursOptimal, ...
    'Reserve-policy test must finish with a proven-optimal solution.');
assert(summary.runStatus=="PASS_STRICT" && summary.strictPass && ...
    ~summary.relaxedPass, ...
    'A reserve-policy solve without fallback must be marked PASS_STRICT.');
assert(summary.mainConclusionEligible && ...
    summary.mainConclusionStatus=="MAIN_CONCLUSION_ELIGIBLE", ...
    'Strict results must be eligible for the main conclusion.');
assert(ledger.reserveTargetEnforced && ...
    ~ledger.reserveTargetFallbackUsed, ...
    'Warning reserve target must be enforced without fallback.');
assert(ledger.runStatus=="PASS_STRICT" && ledger.strictPass && ...
    ~ledger.relaxedPass, ...
    'The hourly ledger must retain the strict-pass status.');
assert(ledger.bessSOC>=0.80-1e-8, ...
    'Warning dispatch must meet the configured BESS reserve target.');
end

function test_unachievable_reserve_target_is_flagged()
cfg=v5_default_config('mechanism_test');
base=base_case(cfg);
strategy=struct( ...
    'id','test_unachievable_typhoon_reserve', ...
    'strategyClass','TEST', ...
    'eventReserveRule',true, ...
    'warningBessReserveTargetSOC',0.50, ...
    'warningH2ReserveTargetKg',cfg.hydrogen.storageMaxKg, ...
    'maxENSMWh',Inf);
[summary,ledger]=c5_run_sequential_hourly( ...
    base,cfg,strategy,"TYPHOON_WARNING",false);
assert(summary.reserveTargetFallbackHours==1, ...
    'An unachievable reserve target must be reported as a fallback.');
assert(summary.runStatus=="PASS_RELAXED" && ~summary.strictPass && ...
    summary.relaxedPass, ...
    'A reserve fallback must be marked PASS_RELAXED, not PASS_STRICT.');
assert(~summary.mainConclusionEligible && ...
    summary.mainConclusionStatus=="EXCLUDED_RELAXED_FALLBACK", ...
    'Relaxed fallback results must be excluded from the main conclusion.');
assert(ledger.reserveTargetFallbackUsed && ...
    ledger.h2ReserveShortfallKg>0, ...
    'The ledger must retain the unmet hydrogen reserve.');
assert(ledger.runStatus=="PASS_RELAXED" && ~ledger.strictPass && ...
    ledger.relaxedPass, ...
    'The hourly ledger must retain the relaxed-pass status.');
assert(~ledger.mainConclusionEligible && ...
    ledger.mainConclusionStatus=="EXCLUDED_RELAXED_FALLBACK", ...
    'The hourly ledger must exclude relaxed fallback results.');
end

