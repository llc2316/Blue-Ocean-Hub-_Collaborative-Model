strategy=struct( ...
    'id','test_normal_state_floor', ...
    'strategyClass','TEST', ...
    'eventReserveRule',true, ...
    'normalStateFloorRule',true, ...
    'maxENSMWh',Inf);
[summary,ledger]=c5_run_sequential_hourly( ...
    base,cfg,strategy,["NORMAL";"NORMAL"],false);
