    'Normal state-floor test must remain strict when no fallback occurs.');
assert(summary.normalStateFloorEnforcedHours==2, ...
    'Normal state floor must be enforced in every normal hour.');
assert(all(ledger.normalStateFloorEnforced), ...
    'Hourly ledger must report normal floor enforcement.');
assert(min(ledger.bessSOC)>=0.50-1e-8, ...
    'Normal state floor must preserve the initial BESS SOC reserve.');
assert(max(ledger.normalBessFloorShortfallMWh)<=1e-8, ...
    'Normal BESS floor shortfall must be zero.');
end

function test_surplus_redispatch_can_start_pem()
cfg=v5_default_config('mechanism_test');
base=base_case(cfg,1,500);
base.cableSendLimitMW=0;
base.gridAcceptLimitMW=0;
base.pMarineDemandMW=0;
base.pComputeFlexibleMaxMW=0;
base.availability.h2Pipe=0;
base.availability.h2Ship=0;
strategy=struct( ...
    'id','test_surplus_redispatch', ...
    'strategyClass','TEST', ...
    'productMixEnabled',true, ...
    'eShare',1,'hShare',0,'cShare',0, ...
    'shareTolerance',0, ...
    'eventReserveRule',false, ...
    'normalStateFloorRule',false, ...
    'surplusRedispatchEnabled',true, ...
    'objectivePrimary','economicNetCostCNY', ...
    'maxENSMWh',Inf);
[summary,ledger]=c5_run_sequential_hourly( ...
    base,cfg,strategy,"NORMAL",false);
assert(summary.auditPass && summary.allHoursOptimal, ...
    'Surplus redispatch test must remain auditable and optimal.');
assert(summary.surplusRedispatchHours==1 && ...
    summary.surplusRedispatchHydrogenMWh>0, ...
    'A realized surplus must trigger PEM redispatch.');
assert(ledger.surplusRedispatchUsed && ...
    ledger.eHydrogenInputMWh>0 && ...
    ledger.surplusRedispatchCurtailmentReductionMWh>0, ...
    'PEM redispatch must absorb surplus and reduce curtailment.');
assert(ledger.ensMWh<=1e-9, ...
    'Surplus redispatch must not create critical ENS.');
end

function test_rolling_window_overcomes_pem_start_cost()
cfg=v5_default_config('mechanism_test');
base=base_case(cfg,(1:6)',20*ones(6,1));
base.initial.bessEnergyMWh=cfg.bess.socMax*cfg.bess.energyMWh- ...
    cfg.bess.gfmAbsorptionReserveEnergyMWh;
base.cableSendLimitMW=0;
base.gridAcceptLimitMW=0;
base.pMarineDemandMW=0;
base.pComputeFlexibleMaxMW=0;
common=struct( ...
    'id','test_rolling_pem', ...
    'strategyClass','TEST', ...
    'productMixEnabled',false, ...
    'forecastMode','PREVIOUS_HOUR_PERSISTENCE', ...
    'initialPlanningCapacityFactor',20/cfg.source.installedMW, ...
    'plannedMinimumAllocationFactor',1, ...
    'plannedShareTolerance',0.05, ...
    'eventReserveRule',false, ...
    'normalStateFloorRule',false, ...
    'surplusRedispatchEnabled',false, ...
    'objectivePrimary','economicNetCostCNY', ...
    'maxENSMWh',Inf);
myopic=common;
myopic.id='test_myopic_pem';
myopic.planningWindowH=1;
[myopicSummary,~]=c5_run_sequential_hourly( ...
    base,cfg,myopic,repmat("NORMAL",6,1),false);

rolling=common;
rolling.planningWindowH=6;
[rollingSummary,rollingLedger]=c5_run_sequential_hourly( ...
    base,cfg,rolling,repmat("NORMAL",6,1),false);

assert(myopicSummary.eHydrogenInputMWh<=1e-8, ...
    'The one-hour economic plan should still avoid the PEM start cost.');
assert(rollingSummary.eHydrogenInputMWh>0 && ...
    rollingSummary.h2ProducedKg>0, ...
    'The 6 h rolling plan must start PEM and produce hydrogen.');
assert(rollingLedger.plannedWindowHydrogenMWh(1)>0 && ...
    rollingLedger.plannedMinimumAllocatedInputMW(1)>0 && ...
    rollingLedger.pElectrolyzerMW(1)>0, ...
    'The first rolling plan must commit and execute first-hour PEM power.');
end

