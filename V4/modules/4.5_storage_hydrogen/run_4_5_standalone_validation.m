function make_seasonal_figure(seasonal,figurePath)
f=figure('Visible','off','Color','white','Position',[100 100 1200 680]);
tiledlayout(f,2,1,'TileSpacing','compact','Padding','compact');
nexttile;
plot(seasonal.response.timeH/24, ...
    seasonal.response.pElectrolyzerMW,'LineWidth',1.2);
hold on;
plot(seasonal.response.timeH/24, ...
    seasonal.h2DeliveredKg*24/1000,'LineWidth',1.2);
ylabel('Power (MW) / delivery (t d^{-1})');
title('8760 h production and delivery mechanism');
legend({'Electrolyzer','H_2 delivery'},'Location','best','Box','off');
grid on;
nexttile;
plot(seasonal.response.timeH/24, ...
    seasonal.response.h2InventoryKg/1000,'LineWidth',1.7);
ylabel('H_2 inventory (t)');
xlabel('Continuous horizon (day)');
title('8760 h seasonal inventory');
grid on;
format_figure(f);
exportgraphics(f,figurePath,'Resolution',220,'BackgroundColor','white');
close(f);
end

function format_figure(f)
ax=findall(f,'Type','axes');
for k=1:numel(ax)
    ax(k).Color='white';
    ax(k).XColor=[0.15 0.15 0.15];
    ax(k).YColor=[0.15 0.15 0.15];
    ax(k).GridColor=[0.70 0.70 0.70];
    ax(k).Title.Color=[0.10 0.10 0.10];
    ax(k).XLabel.Color=[0.10 0.10 0.10];
    ax(k).YLabel.Color=[0.10 0.10 0.10];
end
end
