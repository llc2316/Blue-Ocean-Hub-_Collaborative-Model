function designTable = v5_product_mix_specs(totalProductCapacityMW)
%V5_PRODUCT_MIX_SPECS Chapter-5 product-channel capacity comparison grid.
%
% The share columns describe INPUT-SIDE NAMEPLATE CAPACITY allocation:
%
%   cable send MW + electrolyzer electrical-input MW
%       + compute-facility electrical-input MW = totalProductCapacityMW.
%
% They are not energy-output shares, equal-CAPEX shares, revenue shares, or
% optimized investment decisions. The 22-case grid is adapted from
% LIJunHong659 commit 8da129e1f65005b1847975d78bad343c250f6c24.
% All project-scale capacities remain
% [假设值，待企业调研校准].

if nargin<1 || isempty(totalProductCapacityMW)
    totalProductCapacityMW=420;
end
validateattributes(totalProductCapacityMW,{'numeric'}, ...
    {'scalar','real','finite','positive'});

rows={ ...
    "mix_E100","Power only",1.00,0.00,0.00; ...
    "mix_H100","Hydrogen only",0.00,1.00,0.00; ...
    "mix_C100","Compute only",0.00,0.00,1.00; ...
    "mix_E80_H20","Power + hydrogen, power-led",0.80,0.20,0.00; ...
    "mix_E60_H40","Power + hydrogen",0.60,0.40,0.00; ...
    "mix_E40_H60","Power + hydrogen, H2-led",0.40,0.60,0.00; ...
    "mix_E20_H80","Power + hydrogen, high-H2",0.20,0.80,0.00; ...
    "mix_E80_C20","Power + compute, power-led",0.80,0.00,0.20; ...
    "mix_E60_C40","Power + compute, moderate compute",0.60,0.00,0.40; ...
    "mix_E40_C60","Power + compute, compute-led",0.40,0.00,0.60; ...
    "mix_E20_C80","Power + compute, high-compute",0.20,0.00,0.80; ...
    "mix_H80_C20","Hydrogen + compute, H2-led",0.00,0.80,0.20; ...
    "mix_H60_C40","Hydrogen + compute, moderate compute",0.00,0.60,0.40; ...
    "mix_H40_C60","Hydrogen + compute, compute-led",0.00,0.40,0.60; ...
    "mix_H20_C80","Hydrogen + compute, high-compute",0.00,0.20,0.80; ...
    "mix_E60_H20_C20","Triplex power-biased",0.60,0.20,0.20; ...
    "mix_E50_H30_C20","Triplex power-led",0.50,0.30,0.20; ...
    "mix_E40_H30_C30","Triplex balanced",0.40,0.30,0.30; ...
    "mix_E30_H30_C40","Triplex compute-led",0.30,0.30,0.40; ...
    "mix_E20_H40_C40","Triplex H2/compute-led",0.20,0.40,0.40; ...
    "mix_E20_H60_C20","Triplex H2-biased",0.20,0.60,0.20; ...
    "mix_E20_H20_C60","Triplex high-compute",0.20,0.20,0.60};

scenarioId=string(rows(:,1));
scenarioLabel=string(rows(:,2));
shareElectricity=cell2mat(rows(:,3));
shareHydrogen=cell2mat(rows(:,4));
shareCompute=cell2mat(rows(:,5));
shareSum=shareElectricity+shareHydrogen+shareCompute;
assert(all(abs(shareSum-1)<=1e-12),'Product-mix shares must sum to one.');

totalProductCapacityMW=repmat(double(totalProductCapacityMW), ...
    numel(scenarioId),1);
powerCableMW=totalProductCapacityMW.*shareElectricity;
electrolyzerMW=totalProductCapacityMW.*shareHydrogen;
computeFacilityMW=totalProductCapacityMW.*shareCompute;
secKWhPerKg=repmat(56.77,numel(scenarioId),1);
h2RatedProductionKgPerH=1000*electrolyzerMW./secKWhPerKg;

designTable=table(scenarioId,scenarioLabel,shareElectricity, ...
    shareHydrogen,shareCompute,totalProductCapacityMW,powerCableMW, ...
    electrolyzerMW,computeFacilityMW,secKWhPerKg, ...
    h2RatedProductionKgPerH);
end
